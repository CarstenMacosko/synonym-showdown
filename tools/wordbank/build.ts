// Step 5: compile graded/*.json into the compact data file the game ships with (src/game/data/words.json).
//   - adds a rarity level per synonym from SCOWL (used for bonus points)
//   - drops words on the blocklist (crude or commonly used as insults), whatever the dictionaries say
// Run: npm run words:build

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { GradedFile } from './grade.ts';
import { GRADED_DIR } from './grade.ts';
import { stem } from '../../src/game/match.ts';
import { loadScowl } from './sources.ts';
import { STARTER_TIERS } from './starters.ts';

interface Override {
  set?: Record<string, 1 | 2 | 3>;
  remove?: string[];
}
const OVERRIDES: Record<string, Override> = JSON.parse(readFileSync(join(import.meta.dirname, 'overrides.json'), 'utf8'));

const OUT = join(import.meta.dirname, '../../src/game/data/words.json');

// Real dictionary senses, but not words an all-ages game should accept or have bots say.
const BLOCKLIST = new Set(
  `horny sexy gay queer retarded retard bitchy pissed crap crappy shitty sucky ass arse bastard damn
   wank wanker tits boobs knockers bonk shag butt butthead dick dickhead prick cock balls spaz tranny dyke fag
   faggot slut whore bimbo hussy`
    .trim()
    .split(/\s+/),
);

// Every starter should have at least this many synonyms in a Standard (tiers 1–2) game.
const MIN_STANDARD = 10;

/** SCOWL size -> 1 common, 2 uncommon, 3 rare. */
function rarity(size: number | undefined): 1 | 2 | 3 {
  if (size === undefined || size >= 60) return 3;
  return size <= 40 ? 1 : 2;
}

/** Hand corrections: remove words, regrade them, or add missing ones (to the first meaning). */
function applyOverride(g: GradedFile, o: Override | undefined) {
  if (!o) return;
  const remove = new Set(o.remove ?? []);
  for (const s of g.senses) s.words = s.words.filter((w) => !remove.has(w.word));
  for (const [word, closeness] of Object.entries(o.set ?? {})) {
    const existing = g.senses.flatMap((s) => s.words).find((w) => w.word === word);
    if (existing) existing.closeness = closeness;
    else g.senses[0].words.push({ word, closeness, score: 99, similarity: null, evidence: [] });
  }
}

const scowl = loadScowl();
const starters = Object.values(STARTER_TIERS)
  .flat()
  .map((word) => {
    const g: GradedFile = JSON.parse(readFileSync(join(GRADED_DIR, `${word}.json`), 'utf8'));
    applyOverride(g, OVERRIDES[word]);
    // Thin starters: promote their best-supported distant words to solid until Standard games have enough.
    const all = g.senses.flatMap((s) => s.words).filter((w) => !BLOCKLIST.has(w.word));
    const shortBy = MIN_STANDARD - all.filter((w) => w.closeness <= 2).length;
    if (shortBy > 0) {
      // Only well-supported words: several kinds of evidence and a real similarity to the starter.
      const promote = all
        .filter((w) => w.closeness === 3 && w.evidence.length >= 2 && (w.similarity ?? 0) >= 0.3)
        .sort((a, b) => b.score - a.score)
        .slice(0, shortBy);
      for (const w of promote) w.closeness = 2;
      if (promote.length) console.log(`  ${word}: promoted ${promote.map((w) => w.word).join(', ')}`);
    }
    const senses = g.senses.map((s) => [s.label, s.definition, s.pos]);
    // [word, closeness, sense index, rarity]
    const synonyms = g.senses.flatMap((s, i) =>
      s.words.filter((w) => !BLOCKLIST.has(w.word)).map((w) => [w.word, w.closeness, i, rarity(scowl.get(w.word))]),
    );
    // A decoy must not be a form of a real synonym ("shocked" when "shock" counts), or bots would bluff with real words.
    const stems = new Set(all.map((w) => stem(w.word)));
    const decoys = g.decoys.filter((d) => !BLOCKLIST.has(d) && !stems.has(stem(d)));
    return [g.word, g.tier, senses, synonyms, decoys];
  });

mkdirSync(join(OUT, '..'), { recursive: true });
writeFileSync(
  OUT,
  JSON.stringify({
    about:
      'Generated by tools/wordbank (npm run words:build). Sources: Open English WordNet (CC BY 4.0), Wiktionary via kaikki.org (CC BY-SA 4.0), Moby Thesaurus (public domain), SCOWL (Kevin Atkinson), GloVe (public domain).',
    format: 'starters: [word, tier, senses: [label, definition, pos][], synonyms: [word, closeness, sense, rarity][], decoys][]',
    starters,
  }),
);
const total = starters.reduce((n, s) => n + (s[3] as unknown[]).length, 0);
console.log(`Wrote ${starters.length} starters, ${total} synonyms to ${OUT}`);
